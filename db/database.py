"""PostgreSQL database engine and session management."""

import logging
import os
from contextlib import contextmanager
from typing import Optional

from sqlalchemy import create_engine, inspect
from sqlalchemy.engine import Engine
from sqlalchemy.orm import declarative_base, sessionmaker, Session

DATABASE_URL = os.environ.get("STARGATE_DATABASE_URL", "")

Base = declarative_base()

logger = logging.getLogger("stargate.db")

_engine: Optional[Engine] = None
_SessionLocal: Optional[sessionmaker] = None


def get_engine() -> Engine:
    global _engine
    if _engine is None:
        _engine = create_engine(
            DATABASE_URL,
            pool_size=20,
            max_overflow=10,
            pool_pre_ping=True,
            pool_recycle=3600,
        )
    return _engine


def set_engine(engine: Engine):
    global _engine, _SessionLocal
    _engine = engine
    _SessionLocal = sessionmaker(bind=engine, autocommit=False, autoflush=False)


def get_session_factory() -> sessionmaker:
    global _SessionLocal
    if _SessionLocal is None:
        _SessionLocal = sessionmaker(bind=get_engine(), autocommit=False, autoflush=False)
    return _SessionLocal


def get_db():
    factory = get_session_factory()
    db = factory()
    try:
        yield db
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


@contextmanager
def background_session():
    """Own a worker session without committing work implicitly.

    Request dependencies are generators, not worker session factories. Keep
    ownership through the entire cycle and release it even on cancellation.
    """
    db = get_session_factory()()
    try:
        yield db
    except BaseException:
        db.rollback()
        raise
    finally:
        db.close()


def _alembic_config():
    """The repo's alembic.ini, pointed at whatever engine this process uses."""
    from alembic.config import Config

    cfg = Config(os.path.join(os.path.dirname(os.path.dirname(__file__)), "alembic.ini"))
    if DATABASE_URL:
        cfg.set_main_option("sqlalchemy.url", DATABASE_URL)
    return cfg


def _recorded_revision(engine) -> Optional[str]:
    """The revision in ``alembic_version``, or None if it is not recorded.

    None is not "no database" — it is "this schema has no migration history",
    which is true both of an empty database and of one created by
    ``create_all`` (all tests, every fresh environment, and production until
    it happened to be stamped by hand).
    """
    from sqlalchemy import text

    if "alembic_version" not in inspect(engine).get_table_names():
        return None
    with engine.connect() as conn:
        row = conn.execute(text("SELECT version_num FROM alembic_version")).first()
    return row[0] if row else None


def init_db():
    """Bring the schema to head, for both a migrated and a fresh database.

    Two different databases run this function.

    A database with a recorded revision is migrated: ``alembic upgrade head``
    is the only path that applies data migrations, so it is what a release
    uses.

    A database with no recorded revision cannot be migrated, and this is not
    a fallback that happens to be needed — it is the only thing that can
    work. The baseline revision ``87394f2021f5`` was autogenerated against a
    schema that already existed and contains no ``create_table`` calls at
    all; its first statement drops ``ix_cv_lab`` from a table that does not
    exist yet. Verified on a real PostgreSQL 15 from an empty database:

        psycopg2.errors.UndefinedObject: index "ix_cv_lab" does not exist

    So for an unversioned database the schema is created from the models and
    the revision is *stamped* to head. Stamping matters: without it
    ``alembic_version`` stays empty, the failing chain replays on every
    startup, and every future migration is silently skipped forever — the
    database looks fine because the models are the source of truth, right up
    until a release needs to transform data instead of add an index.
    """
    from db import models  # noqa: F401
    from alembic import command

    engine = get_engine()
    cfg = _alembic_config()

    if _recorded_revision(engine) is not None:
        try:
            command.upgrade(cfg, "head")
        except Exception:
            # Loud, and deliberately not stamped: the revision is still
            # whatever it was, so the next startup retries the real
            # migration rather than believing a schema it did not build.
            logger.error(
                "Alembic upgrade failed; serving on the existing schema. "
                "The migration was NOT applied and will retry on next start.",
                exc_info=True,
            )
            Base.metadata.create_all(bind=engine)
        return

    fresh = not [t for t in inspect(engine).get_table_names() if t != "alembic_version"]
    Base.metadata.create_all(bind=engine)
    command.stamp(cfg, "head")
    if fresh:
        logger.info("Fresh database: schema created from models and stamped at head")
    else:
        logger.warning(
            "Database has tables but no alembic_version: adopted the existing "
            "schema as-is and stamped it at head. Any migration older than "
            "this release was not applied and will not be applied later."
        )

