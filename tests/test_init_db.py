"""`init_db` must work on an empty database, not only on a migrated one.

The baseline revision was autogenerated against a schema that already existed:
`87394f2021f5` contains no `create_table` calls and its first statement is
`op.drop_index(op.f('ix_cv_lab'), table_name='constraint_violations')`. On an
empty database that raises `index "ix_cv_lab" does not exist`, so
`alembic upgrade head` cannot bootstrap a new environment — and because the
failure happened before the version was stamped, `alembic_version` stayed
empty and the same chain replayed (and was swallowed) on every startup. The
schema looked right because `create_all` built it, and every future migration
would have been skipped forever without a word.

These tests pin the two paths: unversioned databases are created and *stamped*,
versioned ones are upgraded.
"""

import logging

import pytest
from sqlalchemy import create_engine, inspect, text


@pytest.fixture
def sqlite_db(tmp_path, monkeypatch):
    """A file-backed SQLite database plus the module pointed at it.

    A file (not ``:memory:``) because alembic opens its own connections.
    """
    from db import database

    url = f"sqlite:///{tmp_path / 'fresh.db'}"
    engine = create_engine(url)
    monkeypatch.setattr(database, "DATABASE_URL", url)
    monkeypatch.setenv("STARGATE_DATABASE_URL", url)
    previous = database._engine
    database.set_engine(engine)
    yield engine
    database._engine = previous


class _Capture(logging.Handler):
    def __init__(self):
        super().__init__()
        self.records = []

    def emit(self, record):
        self.records.append(record)


@pytest.fixture
def db_logs():
    """Records from ``stargate.db`` itself.

    ``caplog`` cannot be used here: ``alembic/env.py`` calls ``fileConfig``,
    which replaces the *root* handlers (caplog's included) mid-test. A
    handler attached to our own logger is untouched by that.
    """
    capture = _Capture()
    log = logging.getLogger("stargate.db")
    previous_level = log.level
    log.addHandler(capture)
    log.setLevel(logging.DEBUG)
    yield capture.records
    log.removeHandler(capture)
    log.setLevel(previous_level)


def _version(engine):
    with engine.connect() as conn:
        if "alembic_version" not in inspect(engine).get_table_names():
            return None
        return conn.execute(text("SELECT version_num FROM alembic_version")).scalar()


def _head():
    from alembic.config import Config
    from alembic.script import ScriptDirectory
    from pathlib import Path

    root = Path(__file__).resolve().parents[1]
    cfg = Config(str(root / "alembic.ini"))
    cfg.set_main_option("script_location", str(root / "alembic"))
    return ScriptDirectory.from_config(cfg).get_current_head()


def test_an_empty_database_is_created_and_stamped_at_head(sqlite_db):
    from db import database

    assert inspect(sqlite_db).get_table_names() == []

    database.init_db()

    tables = set(inspect(sqlite_db).get_table_names())
    assert {"runs", "stages", "evaluations", "alembic_version"} <= tables
    # The stamp is the whole point: without it the next startup replays a
    # chain that cannot run, and every later migration is skipped.
    assert _version(sqlite_db) == _head()


def test_a_second_startup_takes_the_upgrade_path_and_does_not_recreate(sqlite_db):
    from db import database

    database.init_db()
    first = _version(sqlite_db)

    database.init_db()  # no exception, no second stamp, no schema churn

    assert _version(sqlite_db) == first == _head()


def test_a_database_with_tables_but_no_version_is_adopted_and_stamped(sqlite_db, db_logs):
    from db import database

    database.Base.metadata.create_all(bind=sqlite_db)
    with sqlite_db.begin() as conn:
        conn.execute(text("DROP TABLE IF EXISTS alembic_version"))
    assert _version(sqlite_db) is None

    database.init_db()

    assert _version(sqlite_db) == _head()
    warnings = [r for r in db_logs if r.levelname == "WARNING"]
    assert warnings and "no alembic_version" in warnings[0].getMessage()


def test_a_versioned_database_is_upgraded_not_adopted(sqlite_db, monkeypatch):
    """A recorded revision means real migrations run — create_all is not used."""
    from db import database

    database.Base.metadata.create_all(bind=sqlite_db)
    with sqlite_db.begin() as conn:
        conn.execute(text("CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL)"))
        conn.execute(text("INSERT INTO alembic_version VALUES ('r9a0b1c2d3e4')"))

    calls = []
    monkeypatch.setattr(
        database.Base.metadata, "create_all",
        lambda *a, **kw: calls.append("create_all"),
    )

    database.init_db()

    assert calls == [], "create_all must not run against a versioned database"
    assert _version(sqlite_db) == _head()


def test_a_failed_upgrade_is_loud_and_leaves_the_revision_alone(sqlite_db, monkeypatch, db_logs):
    """Never stamp a schema you did not migrate; retry on the next start."""
    from db import database

    database.Base.metadata.create_all(bind=sqlite_db)
    with sqlite_db.begin() as conn:
        conn.execute(text("CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL)"))
        conn.execute(text("INSERT INTO alembic_version VALUES ('r9a0b1c2d3e4')"))

    import alembic.command as command

    def boom(*a, **kw):
        raise RuntimeError("migration exploded")

    monkeypatch.setattr(command, "upgrade", boom)

    database.init_db()  # must not raise: the API still has to serve

    assert _version(sqlite_db) == "r9a0b1c2d3e4"
    errors = [r for r in db_logs if r.levelname == "ERROR"]
    assert errors and "NOT applied" in errors[0].getMessage()
